/**
 * Converts an array of objects to a CSV string.
 * @param data The array of objects to convert.
 * @returns The CSV formatted string.
 */
function arrayToCsv(data: PintuAirData[]): string {
    if (data.length === 0) {
        return "";
    }

    // 2. Generate the Header Row (Column Names)
    // Use Object.keys() from the first object to get all column names.
    const headers = Object.keys(data[0]);
    const headerRow = headers.join(',') + '\n';

    // 3. Generate the Data Rows
    const dataRows = data.map(obj => {
        // Map each header key to its corresponding value in the object.
        const values = headers.map(key => {
            let value = String(obj[key as keyof PintuAirData]);

            // Basic CSV sanitization: enclose values containing commas, newlines, or double-quotes in double-quotes.
            if (value.includes(',') || value.includes('\n') || value.includes('"')) {
                // Escape existing double quotes by doubling them, then wrap the whole string in double quotes.
                value = `"${value.replace(/"/g, '""')}"`;
            }
            return value;
        });
        return values.join(',');
    }).join('\n');

    // Combine header and data
    return headerRow + dataRows;
}

async function exportCsv() {
    const csvString = arrayToCsv(data);
    const outputPath = join(process.cwd(), 'water_gate_data.csv');

    console.log('Generating CSV content...');

    try {
        // 4. Write the CSV string to a file using Bun.write
        await Bun.write(outputPath, csvString);
        console.log(`✅ Success! Data written to: ${outputPath}`);

    } catch (error) {
        console.error(`❌ Failed to write file:`, error);
    }
}

